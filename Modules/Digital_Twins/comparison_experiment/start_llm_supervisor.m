function process = start_llm_supervisor(output_dir)
%START_LLM_SUPERVISOR Start the existing Python UDP runner asynchronously.

this_dir = fileparts(mfilename('fullpath'));
dt_dir = fileparts(this_dir);
project_root = fileparts(fileparts(dt_dir));
python_path = fullfile(project_root, '.venv', 'Scripts', 'python.exe');
runner_path = fullfile(project_root, 'run_dt_runner.py');

if ~isfile(python_path)
    error(['Python environment not found: %s\nRun setup_environment.bat ' ...
        '--no-tests before the comparison.'], python_path);
end
if ~isfile(runner_path)
    error('Runner entry point not found: %s', runner_path);
end
if ~isfolder(output_dir)
    mkdir(output_dir);
end

trace_path = fullfile(output_dir, 'llm_trace.jsonl');
runner_csv = fullfile(output_dir, 'llm_runner.csv');
runner_report = fullfile(output_dir, 'llm_runner_report.md');
if isfile(trace_path)
    delete(trace_path);
end

arguments = strjoin({ ...
    quote(runner_path), ...
    '--backend udp', ...
    '--policy llm', ...
    '--llm-base-url http://127.0.0.1:1234/v1', ...
    '--llm-model llama-3-groq-8b-tool-use', ...
    '--llm-api-key lm-studio', ...
    '--llm-temperature 0', ...
    '--llm-max-tokens 120', ...
    '--llm-command-limit 480', ...
    ['--llm-log ' quote(trace_path)], ...
    '--llm-verbose', ...
    '--tick-seconds 10', ...
    '--startup-grace-seconds 1', ...
    '--max-sim-seconds 120', ...
    '--success-hold-seconds 999', ...
    '--soc-min 40', ...
    '--soc-max 80', ...
    '--bus-nominal 400', ...
    '--max-p-batt 480', ...
    '--max-p-batt-step 100', ...
    '--source-power-limit 500', ...
    '--source-power-margin 25', ...
    '--charge-power-margin 25', ...
    '--charge-recovery-hold-seconds 0', ...
    '--post-discharge-charge-hold-seconds 0', ...
    '--udp-command-host 127.0.0.1', ...
    '--udp-command-port 55000', ...
    '--udp-observation-host 0.0.0.0', ...
    '--udp-observation-port 55001', ...
    '--udp-timeout 30', ...
    '--udp-reset-timeout 180', ...
    '--udp-command-resend-period 0.25', ...
    ['--csv ' quote(runner_csv)], ...
    ['--report ' quote(runner_report)]}, ' ');

start_info = System.Diagnostics.ProcessStartInfo();
start_info.FileName = python_path;
start_info.Arguments = arguments;
start_info.WorkingDirectory = project_root;
start_info.UseShellExecute = false;
start_info.CreateNoWindow = true;
start_info.RedirectStandardOutput = true;
start_info.RedirectStandardError = true;
process = System.Diagnostics.Process.Start(start_info);
pause(0.5);
end


function value = quote(value)
value = ['"' char(value) '"'];
end
